// Package render renders the server-side configs for amnezia-mesh from
// config/server.env + config/peers.db:
//
//	awg0.conf    - full AWG server config (interface + peers), mode 0600
//	dnsmasq.conf - dnsmasq for MagicDNS (sidecar shares awg netns)
//	start.sh     - container entrypoint: awg-quick + iptables bootstrap
//
// Output is byte-identical to the Python reference (awg_mesh/render.py) —
// the golden files under testdata/fixtures/golden are the contract.
package render

import (
	"fmt"
	"net/netip"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/alexpozdnyakof/amnezia-mesh-go/internal/envfile"
	"github.com/alexpozdnyakof/amnezia-mesh-go/internal/peers"
)

// obfKeys are the AmneziaWG obfuscation parameter names, in render order.
// Shared with adopt (conf key → OBF_*) — single source of truth for the set.
var obfKeys = []string{
	"Jc", "Jmin", "Jmax", "S1", "S2", "S3", "S4",
	"H1", "H2", "H3", "H4", "HeaderProtectionKey",
	"ContentPaddingAddition", "RekeyAfterTime", "RekeyTimeout",
	"RejectAfterTime", "KeepaliveTimeout", "MaxHandshakeAttempts",
	"RandomTrailers", "DisableCookies",
}

// rawGet mirrors Python's env.get(key, def): the default applies only when
// the key is absent, not when it holds an empty string.
func rawGet(env map[string]string, key, def string) string {
	if v, ok := env[key]; ok {
		return v
	}
	return def
}

func obfLines(env map[string]string, indent string) []string {
	var out []string
	for _, k := range obfKeys {
		if v := env["OBF_"+strings.ToUpper(k)]; v != "" {
			out = append(out, indent+k+" = "+v)
		}
	}
	return out
}

// parseNetwork mirrors Python's ipaddress.ip_network(subnet) with the
// default strict=True: host bits set → error.
func parseNetwork(subnet string) (netip.Prefix, error) {
	p, err := netip.ParsePrefix(subnet)
	if err != nil {
		return netip.Prefix{}, err
	}
	if p.Addr() != p.Masked().Addr() {
		return netip.Prefix{}, fmt.Errorf("%s has host bits set", subnet)
	}
	return p.Masked(), nil
}

// RenderAwg0 renders the full AWG server config (interface + peers).
func RenderAwg0(env map[string]string, plist []peers.Peer) (string, error) {
	p, err := parseNetwork(env["AWG_MESH_SUBNET"])
	if err != nil {
		return "", err
	}
	priv, ok := env["SERVER_PRIV"]
	if !ok {
		return "", fmt.Errorf("SERVER_PRIV missing in server.env")
	}
	keepalive := rawGet(env, "SERVER_KEEPALIVE", "25")
	lines := []string{
		"# Generated by amnezia-mesh (render.py). Do not edit by hand:",
		"# changes are overwritten on every `awg-mesh peer` operation.",
		"[Interface]",
		"PrivateKey = " + priv,
		fmt.Sprintf("Address = %s/%d", p.Addr().Next().String(), p.Bits()),
		"ListenPort = " + rawGet(env, "LISTEN_PORT", "41480"),
		"MTU = " + rawGet(env, "MTU", "1280"),
	}
	lines = append(lines, obfLines(env, "")...)
	for _, pr := range plist {
		lines = append(lines,
			"[Peer]",
			fmt.Sprintf("# %s (added %s)", pr.Name, pr.Created),
			"PublicKey = "+pr.Pub,
			"PresharedKey = "+pr.PSK,
			"AllowedIPs = "+pr.IP+"/32",
			"PersistentKeepalive = "+keepalive,
			"",
		)
	}
	return strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n", nil
}

// RenderDnsmasq renders dnsmasq config for MagicDNS.
func RenderDnsmasq(env map[string]string, plist []peers.Peer) (string, error) {
	p, err := parseNetwork(env["AWG_MESH_SUBNET"])
	if err != nil {
		return "", err
	}
	domain := rawGet(env, "AWG_MESH_DOMAIN", "awg")
	lines := []string{
		"# Generated by amnezia-mesh (render.py).",
		"no-resolv",
		"listen-address=127.0.0.1",
		"interface=awg0",
		"bind-interfaces",
		"domain-needed",
		"bogus-priv",
		"server=" + rawGet(env, "AWG_MESH_DNS1", "1.1.1.1"),
	}
	if v := env["AWG_MESH_DNS2"]; v != "" {
		lines = append(lines, "server="+v)
	}
	lines = append(lines, "host-record=hub."+domain+","+p.Addr().Next().String())
	for _, pr := range plist {
		lines = append(lines, "host-record="+pr.Name+"."+domain+","+pr.IP)
	}
	return strings.Join(lines, "\n") + "\n", nil
}

const startShTemplate = `#!/bin/sh
# Generated by amnezia-mesh (render.py). Subnet: {subnet}.
echo "amnezia-mesh: starting"
sysctl -w net.ipv4.ip_forward=1 2>/dev/null || true
awg-quick down /opt/amnezia/awg/awg0.conf 2>/dev/null
awg-quick up /opt/amnezia/awg/awg0.conf || { echo "amnezia-mesh: awg-quick failed"; exit 1; }

SUBNET={subnet}
IFACE=$(ip route show default 2>/dev/null | awk 'NR==1 {print $5}')

iptables -A INPUT -i awg0 -j ACCEPT
iptables -A FORWARD -i awg0 -j ACCEPT
iptables -A OUTPUT -o awg0 -j ACCEPT
if [ -n "$IFACE" ]; then
  iptables -A FORWARD -i awg0 -o "$IFACE" -s "$SUBNET" -j ACCEPT
  iptables -t nat -A POSTROUTING -s "$SUBNET" -o "$IFACE" -j MASQUERADE
fi
iptables -A FORWARD -m state --state ESTABLISHED,RELATED -j ACCEPT

# MSS clamp both directions: {mss} = MTU {mtu} - 40. Explicit --set-mss,
# NOT --clamp-mss-to-pmtu (that one uses the outgoing route MTU and misses
# the download direction).
iptables -t mangle -A FORWARD -i awg0 -p tcp --tcp-flags SYN,RST SYN \
  -m tcpmss --mss {mss_hi}:65535 -j TCPMSS --set-mss {mss}
iptables -t mangle -A FORWARD -o awg0 -p tcp --tcp-flags SYN,RST SYN \
  -m tcpmss --mss {mss_hi}:65535 -j TCPMSS --set-mss {mss}
{rdp_rule}
exec tail -f /dev/null
`

// RenderStartSh renders the container entrypoint (awg-quick + iptables
// bootstrap). Byte-identical to Python's f-string template, including the
// blank line where the optional RDP rule would sit.
func RenderStartSh(env map[string]string) (string, error) {
	subnet := env["AWG_MESH_SUBNET"]
	mtu, err := strconv.Atoi(rawGet(env, "MTU", "1280"))
	if err != nil {
		return "", err
	}
	mss := mtu - 40
	rdpRule := ""
	if rawGet(env, "AWG_MESH_RDP_REJECT", "0") == "1" {
		rdpRule = "# RDP UDP/3389 reject: forces instant TCP fallback, avoids starving\n" +
			"# graphics channel across the tunnel (see README).\n" +
			"iptables -I FORWARD 1 -i awg0 -p udp --dport 3389 -j REJECT --reject-with icmp-port-unreachable"
	}
	r := strings.NewReplacer(
		"{subnet}", subnet,
		"{mtu}", strconv.Itoa(mtu),
		"{mss}", strconv.Itoa(mss),
		"{mss_hi}", strconv.Itoa(mss+1),
		"{rdp_rule}", rdpRule,
	)
	return r.Replace(startShTemplate), nil
}

// RenderAll writes awg0.conf (0600), dnsmasq.conf and start.sh (0755) into
// root/config and returns the peer count.
func RenderAll(root string) (int, error) {
	cfgDir := filepath.Join(root, "config")
	env, err := envfile.Load(filepath.Join(cfgDir, "server.env"))
	if err != nil {
		return 0, err
	}
	plist, err := peers.Load(filepath.Join(cfgDir, "peers.db"))
	if err != nil {
		return 0, err
	}
	awg0, err := RenderAwg0(env, plist)
	if err != nil {
		return 0, err
	}
	dnsmasq, err := RenderDnsmasq(env, plist)
	if err != nil {
		return 0, err
	}
	start, err := RenderStartSh(env)
	if err != nil {
		return 0, err
	}
	// 0o600: awg-quick warns on world-readable configs that contain secrets.
	if err := writeFile(filepath.Join(cfgDir, "awg0.conf"), awg0, 0o600); err != nil {
		return 0, err
	}
	if err := writeFile(filepath.Join(cfgDir, "dnsmasq.conf"), dnsmasq, 0); err != nil {
		return 0, err
	}
	if err := writeFile(filepath.Join(cfgDir, "start.sh"), start, 0o755); err != nil {
		return 0, err
	}
	return len(plist), nil
}

func writeFile(path, content string, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return err
	}
	if mode != 0 {
		return os.Chmod(path, mode)
	}
	return nil
}
